/**
 * Regenerates src/data/popular-<eco>.ts (the typosquat check's name lists) from
 * public download rankings. Network at release time only: run by a person,
 * reviewed, committed (RELEASING.md, "Before the release"). Never run by the firewall or its tests.
 *
 *   node scripts/gen-popular.mjs [--eco npm|pypi|crates] [--targets 5000] [--known 20000]
 *
 * Sources [verify each before a release; the choice of source is still open]:
 *   PyPI   hugovk/top-pypi-packages, 30-day downloads (JSON, up to 15,000 rows)
 *   npm    the registry search API ranked by popularity (250 per page)
 *   crates crates.io API sorted by downloads (100 per page; needs a User-Agent)
 *   RubyGems has no public top-downloads list; its seed list is kept by hand.
 * The names in the existing file's `known` list are kept (they are reviewed near-neighbours).
 */
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const arg = (n, d) => {
  const i = args.indexOf(n);
  return i === -1 ? d : args[i + 1];
};
const ecos = arg("--eco", "npm,pypi,crates").split(",");
const nTargets = Number(arg("--targets", "5000"));
const nKnown = Number(arg("--known", "20000"));
const UA = { "user-agent": "launchsafe-agent-firewall gen-popular (release script)" };
const today = new Date().toISOString().slice(0, 10);

async function json(url) {
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.json();
}

async function pypi() {
  const url = "https://hugovk.github.io/top-pypi-packages/top-pypi-packages-30-days.min.json";
  const d = await json(url);
  return { source: url, names: d.rows.map((r) => r.project) };
}

async function npm(limit) {
  const names = [];
  const base = "https://registry.npmjs.org/-/v1/search?text=not:unstable&popularity=1.0&quality=0.0&maintenance=0.0&size=250";
  for (let from = 0; names.length < limit && from < limit; from += 250) {
    const d = await json(`${base}&from=${from}`);
    if (d.objects.length === 0) break;
    for (const o of d.objects) names.push(o.package.name);
  }
  return { source: `${base} (paged)`, names };
}

async function crates(limit) {
  const names = [];
  const base = "https://crates.io/api/v1/crates?sort=downloads&per_page=100";
  for (let page = 1; names.length < limit; page++) {
    const d = await json(`${base}&page=${page}`);
    if (d.crates.length === 0) break;
    for (const c of d.crates) names.push(c.id);
    await new Promise((r) => setTimeout(r, 1000)); // crates.io asks for one request per second
  }
  return { source: `${base} (paged)`, names };
}

const FILES = { npm: ["popular-npm.ts", "NPM", "npm"], pypi: ["popular-pypi.ts", "PYPI", "PyPI"], crates: ["popular-crates.ts", "CRATES", "crates.io"] };

function existingKnown(file) {
  try {
    const t = readFileSync(new URL(`../src/data/${file}`, import.meta.url), "utf8");
    const m = /known: names\(`([\s\S]*?)`\)/.exec(t);
    return m === null ? [] : m[1].split(/\s+/).filter(Boolean);
  } catch {
    return [];
  }
}

const wrap = (list) => list.reduce((lines, n) => {
  const last = lines[lines.length - 1];
  if (last.length + n.length + 1 > 140) lines.push(n);
  else lines[lines.length - 1] = last === "" ? n : `${last} ${n}`;
  return lines;
}, [""]).map((l) => `    ${l}`).join("\n");

for (const eco of ecos) {
  const [file, constName, label] = FILES[eco] ?? [];
  if (file === undefined) throw new Error(`unknown --eco ${eco}`);
  const { source, names } = eco === "pypi" ? await pypi() : eco === "npm" ? await npm(nKnown) : await crates(nKnown);
  const uniq = [...new Set(names)];
  const targets = uniq.slice(0, nTargets);
  const known = [...new Set([...uniq.slice(nTargets, nKnown), ...existingKnown(file)])].filter((n) => !targets.includes(n));
  const text = `/**
 * Popular ${label} package names for the typosquat check.
 *
 * Source: ${source}
 * Date: ${today}. Generated by scripts/gen-popular.mjs; ${targets.length} targets, ${known.length} known.
 */

import { names } from "./names.js";

export const ${constName} = {
  source: ${JSON.stringify(source)},
  date: "${today}",
  targets: names(\`
${wrap(targets)}
  \`),
  known: names(\`
${wrap(known)}
  \`),
};
`;
  writeFileSync(new URL(`../src/data/${file}`, import.meta.url), text);
  console.log(`${file}: ${targets.length} targets, ${known.length} known (${source})`);
}
console.log("Now run npm test (the typosquat tests check that no listed name is flagged) and review the diff.");
