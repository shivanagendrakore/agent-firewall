/**
 * Vendors the agent-safety rule catalogue's text (id, title, severity, impact,
 * fix) from LaunchSafe's agent-safety package (rules.ts) into
 * src/vendor/agent-safety-rules.ts, for `explain ls-agent-...`. Only the
 * documentation is copied, not the detectors (the analyzer is vendored separately by
 * scripts/sync-agent-safety.mjs). Apache-2.0.
 *
 *   node scripts/sync-agent-safety-rules.mjs [path/to/upstream-checkout] [--check]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const args = process.argv.slice(2);
const check = args.includes("--check");
const given = args.find((a) => !a.startsWith("--")) ?? process.env.LAUNCHSAFE_APP_DIR;
if (given === undefined) {
  console.error("Pass the path to a checkout of LaunchSafe's product repository, or set LAUNCHSAFE_APP_DIR.");
  process.exit(2);
}
const app = resolve(given);
const src = join(app, "packages", "agent-safety", "src", "rules.ts");
const m = await import(src);
let commit = "unknown";
try {
  commit = execFileSync("git", ["log", "-1", "--format=%h", "--", "packages/agent-safety/src/rules.ts"], { cwd: app, encoding: "utf8" }).trim();
} catch {
  // Not a git checkout.
}
const rules = Object.values(m.RULES).map((r) => ({ id: r.id, family: r.family, title: r.title, severity: r.severity, cwe: r.cwe, impact: r.impact, fix: r.fix }));
rules.sort((a, b) => a.id.localeCompare(b.id));
const out = `/**
 * Vendored from LaunchSafe's agent-safety package (rules.ts, rules ${m.RULES_VERSION}), Apache-2.0, at commit ${commit}.
 * Copyright LaunchSafe. Licensed under the Apache License, Version 2.0.
 * Generated by scripts/sync-agent-safety-rules.mjs; do not edit by hand. Text only: the detectors are not vendored.
 */

export interface VendoredAgentRule {
  id: string;
  family: string;
  title: string;
  severity: string;
  cwe: string | null;
  impact: string;
  fix: string;
}

export const AGENT_SAFETY_RULES_VERSION = ${JSON.stringify(m.RULES_VERSION)};

export const AGENT_SAFETY_RULES: readonly VendoredAgentRule[] = ${JSON.stringify(rules, null, 2)};
`;
const target = join(import.meta.dirname, "..", "src", "vendor", "agent-safety-rules.ts");
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  current = "";
}
if (check) {
  if (current !== out) {
    console.error("src/vendor/agent-safety-rules.ts is out of date: run node scripts/sync-agent-safety-rules.mjs");
    process.exit(1);
  }
} else writeFileSync(target, out);
