// The hook runs as a new process on every tool call, and loading its ~150 dist modules one by one (a
// resolve, a realpath, a read and a compile each) is about a third of what a call costs. This writes the
// hook's module graph as one file, dist/hook/bundle.js, which the CLI's hook command loads instead of
// dist/hook/claude.js (src/climain.ts). Same code, same order of evaluation; only the packaging differs.
//
// The bundler is rolldown, a devDependency (package.json). Without it the build fails, so a package is never
// built or released without the bundle. The CLI can still load the modules one by one (a hand-made dist with
// no bundle works), but a release must not ship that slower path by accident.
//
// import.meta.url is the one thing that changes meaning in a bundle (two modules locate files from it:
// installDir() in runtime/layout.js and the vault's CLI path in hook/vault.js). Each module's
// import.meta.url is rewritten to its own dist file's URL, computed from the bundle's location at run time,
// so the paths stay right wherever the package is installed.
import { existsSync, rmSync, statSync } from "node:fs";
import { dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const dist = fileURLToPath(new URL("../dist/", import.meta.url));
const entry = `${dist}hook/claude.js`;
const out = `${dist}hook/bundle.js`;

if (!existsSync(entry)) throw new Error("dist/hook/claude.js is missing: run tsc first");

let rolldown;
try {
  ({ rolldown } = await import("rolldown"));
} catch (e) {
  rmSync(out, { force: true });
  console.error(`bundle-hook: rolldown is not available (${e.message.split("\n")[0]}). It is a devDependency: run npm ci. dist/hook/bundle.js was not written.`);
  process.exit(1);
}

const META = /\bimport\.meta\.url\b/;
const keepModuleUrl = {
  name: "keep-module-url",
  transform(code, id) {
    if (!META.test(code)) return null;
    const rel = relative(dirname(out), id).split(sep).join("/");
    return { code: code.replaceAll(new RegExp(META, "g"), `new URL(${JSON.stringify(rel)}, import.meta.url).href`), map: null };
  },
};

const bundle = await rolldown({ input: entry, platform: "node", plugins: [keepModuleUrl], logLevel: "warn" });
await bundle.write({ file: out, format: "esm", codeSplitting: false, banner: "// Generated by scripts/bundle-hook.mjs from dist/hook/claude.js and its imports. Do not edit." });
await bundle.close();
if (!existsSync(out)) throw new Error("bundle-hook: rolldown finished but dist/hook/bundle.js is missing");
// The CLI uses the bundle only when it is newer than the modules it was made from (src/climain.ts).
if (statSync(out).mtimeMs < statSync(entry).mtimeMs) throw new Error("bundle-hook: the bundle is older than dist/hook/claude.js");
