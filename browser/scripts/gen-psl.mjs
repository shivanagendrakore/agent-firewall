#!/usr/bin/env node
/**
 * Generates src/engine/psl-data.ts, an offline copy of the Public Suffix List
 * (ICANN and private sections), from one pinned commit of publicsuffix/list.
 * The extension never fetches anything at run time; only this script does, and
 * only when run by a person.
 *
 *   node scripts/gen-psl.mjs           fetch the pinned commit and write the module
 *   node scripts/gen-psl.mjs --check   verify the committed module: its integrity digest, and
 *                                      (when the network is reachable) that it is exactly what the
 *                                      pinned commit generates
 *
 * To update the list: change PSL_COMMIT, run the script, commit the result.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { domainToASCII } from "node:url";
import { fileURLToPath } from "node:url";

const PSL_COMMIT = "3929462652695bad04f0a27afb600974014a3c8b";
const SOURCE = `https://raw.githubusercontent.com/publicsuffix/list/${PSL_COMMIT}/public_suffix_list.dat`;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "engine", "psl-data.ts");

/** Rules (punycode, lower case) split into plain, wildcard ("*.x" stored as "x") and exception ("!x" stored as "x"). */
export function parse(text) {
  const plain = new Set();
  const wild = new Set();
  const except = new Set();
  for (const raw of text.split("\n")) {
    const line = raw.trim().split(/\s/)[0] ?? "";
    if (line === "" || line.startsWith("//")) continue;
    let rule = line;
    let kind = plain;
    if (rule.startsWith("!")) {
      kind = except;
      rule = rule.slice(1);
    } else if (rule.startsWith("*.")) {
      kind = wild;
      rule = rule.slice(2);
    }
    const ascii = domainToASCII(rule.toLowerCase());
    if (ascii === "") throw new Error(`cannot convert rule ${line}`);
    kind.add(ascii);
  }
  const sorted = (s) => [...s].sort();
  return { plain: sorted(plain), wild: sorted(wild), except: sorted(except) };
}

function digestOf(p) {
  return createHash("sha256").update(JSON.stringify([p.plain, p.wild, p.except])).digest("hex");
}

export function render(p) {
  const block = (name, list) => `export const ${name}: string = ${JSON.stringify(list.join("\n"))};\n`;
  return [
    "// GENERATED by scripts/gen-psl.mjs. Do not edit; `node scripts/gen-psl.mjs --check` verifies it.",
    `// Public Suffix List (ICANN and private sections), publicsuffix/list at commit ${PSL_COMMIT}, MPL-2.0.`,
    "// The Public Suffix List is MPL-2.0 (https://mozilla.org/MPL/2.0/), (c) the Public Suffix List authors, https://publicsuffix.org/list/; see NOTICE.",
    `// Rules: ${p.plain.length} plain, ${p.wild.length} wildcard, ${p.except.length} exception. Newline-separated, punycode, sorted.`,
    `export const PSL_COMMIT = ${JSON.stringify(PSL_COMMIT)};`,
    `export const PSL_DIGEST = ${JSON.stringify(digestOf(p))};`,
    "/** Plain rules: the host is a public suffix. */",
    block("PSL_PLAIN", p.plain),
    '/** Wildcard rules, stored without the "*." (so "ck" stands for "*.ck"). */',
    block("PSL_WILDCARD", p.wild),
    "/** Exception rules, stored without the \"!\". */",
    block("PSL_EXCEPTION", p.except),
  ].join("\n");
}

async function fetchList() {
  const res = await globalThis.fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch ${SOURCE}: ${res.status}`);
  return res.text();
}

const check = process.argv.includes("--check");
const current = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return null;
  }
})();

if (!check) {
  const out = render(parse(await fetchList()));
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${out.length} bytes) from ${PSL_COMMIT}`);
} else {
  if (current === null) {
    console.error("psl-data.ts is missing");
    process.exit(1);
  }
  const m = /PSL_COMMIT = "([0-9a-f]+)"/.exec(current);
  if (m?.[1] !== PSL_COMMIT) {
    console.error(`psl-data.ts is generated from ${m?.[1] ?? "?"}, the script pins ${PSL_COMMIT}`);
    process.exit(1);
  }
  const section = (name) => {
    const mm = new RegExp(`export const ${name}: string = (".*");`).exec(current);
    return mm === null ? null : JSON.parse(mm[1]).split("\n");
  };
  const have = { plain: section("PSL_PLAIN"), wild: section("PSL_WILDCARD"), except: section("PSL_EXCEPTION") };
  const dig = /PSL_DIGEST = "([0-9a-f]+)"/.exec(current)?.[1];
  if (have.plain === null || have.wild === null || have.except === null || dig !== digestOf(have)) {
    console.error("psl-data.ts does not match its own integrity digest");
    process.exit(1);
  }
  try {
    const expected = render(parse(await fetchList()));
    if (expected !== current) {
      console.error("psl-data.ts differs from what the pinned commit generates; run `node scripts/gen-psl.mjs`");
      process.exit(1);
    }
    console.log(`psl-data.ts matches ${PSL_COMMIT}`);
  } catch (e) {
    console.log(`psl-data.ts matches its integrity digest; the byte comparison against ${PSL_COMMIT} was skipped (${e instanceof Error ? e.message : e})`);
  }
}
